/**
 * Rebuilds src/data/guides/index.ts and src/data/generated/index.ts from the JSON files in those folders,
 * so guides are statically imported and bundled.  Usage: npx tsx scripts/build-registry.ts
 */
import { readdirSync, writeFileSync } from "fs";
import path from "path";

const root = path.join(__dirname, "..", "src", "data");

function build(folder: string, exportName: string, header: string) {
  const dir = path.join(root, folder);
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort();
  const ident = (f: string) => "g_" + f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_");
  const lines = [
    `import type { Guide } from "@/lib/guide-schema";`,
    ...files.map((f) => `import ${ident(f)} from "./${f}";`),
    "",
    header,
    `export const ${exportName}: Record<string, Guide> = {`,
    ...files.map((f) => `  ${JSON.stringify(f.replace(/\.json$/, ""))}: ${ident(f)} as unknown as Guide,`),
    "};",
    "",
  ];
  writeFileSync(path.join(dir, "index.ts"), lines.join("\n"));
  console.log(`${folder}/index.ts: ${files.length} guide(s)`);
}

build(
  "guides",
  "curatedGuides",
  "// Curated guides are hand-checked against official sources and real setup attempts.\n// Generated by scripts/build-registry.ts. Do not edit by hand.",
);
build(
  "generated",
  "seedGeneratedGuides",
  "// Agent-generated guides produced ahead of time and bundled so the library has examples. Live runs override these.\n// Generated by scripts/build-registry.ts. Do not edit by hand.",
);
